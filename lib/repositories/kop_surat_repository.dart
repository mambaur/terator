import 'dart:convert';
import 'dart:io';

import 'package:flutter/foundation.dart';
import 'package:flutter/widgets.dart';
import 'package:image_picker/image_picker.dart';
import 'package:path_provider/path_provider.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'package:terator/data/kop_surat_designs.dart';
import 'package:terator/models/kop_surat_model.dart';

/// Stores the kop surat configuration locally:
/// - text fields + chosen design in SharedPreferences (JSON)
/// - logo images (main + optional secondary) copied into the app documents directory
/// - the set of letter keys whose "Gunakan Kop Surat" switch is on
class KopSuratRepository {
  static const String _configKey = 'kop_surat_config';
  static const String _enabledLettersKey = 'kop_surat_enabled_letters';

  Future<KopSuratModel> get() async {
    final prefs = await SharedPreferences.getInstance();
    final raw = prefs.getString(_configKey);
    if (raw == null) return const KopSuratModel();
    try {
      return KopSuratModel.fromJson(jsonDecode(raw));
    } catch (_) {
      return const KopSuratModel();
    }
  }

  Future<void> save(KopSuratModel kop) async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_configKey, jsonEncode(kop.toJson()));
  }

  /// Copies the picked image into app storage so it survives the picker's
  /// temp file being cleaned up. Returns the stored path.
  /// On web (dev-only, no file system) the logo is stored inline as a
  /// `data:` URI instead.
  Future<String> storeLogo(String sourcePath) async {
    if (kIsWeb) {
      final bytes = await XFile(sourcePath).readAsBytes();
      return 'data:image/png;base64,${base64Encode(bytes)}';
    }
    final dir = await getApplicationDocumentsDirectory();
    final ext = sourcePath.contains('.') ? sourcePath.split('.').last : 'png';
    // Unique name so Image.file doesn't serve a cached old logo.
    final target = File(
        '${dir.path}/kop_logo_${DateTime.now().millisecondsSinceEpoch}.$ext');
    await File(sourcePath).copy(target.path);
    return target.path;
  }

  Future<void> deleteLogo(String? path) async {
    if (path == null) return;
    if (_isDataUri(path)) {
      _memoryImages.remove(path);
      return;
    }
    final file = File(path);
    if (await file.exists()) await file.delete();
  }

  Future<Set<String>> enabledLetters() async {
    final prefs = await SharedPreferences.getInstance();
    return (prefs.getStringList(_enabledLettersKey) ?? []).toSet();
  }

  Future<void> setEnabled(String letterKey, bool enabled) async {
    final prefs = await SharedPreferences.getInstance();
    final keys = (prefs.getStringList(_enabledLettersKey) ?? []).toSet();
    enabled ? keys.add(letterKey) : keys.remove(letterKey);
    await prefs.setStringList(_enabledLettersKey, keys.toList());
  }

  /// Kop HTML for [letterKey], or '' when the switch is off, kop isn't
  /// configured, or the user isn't premium.
  Future<String> htmlForLetter(String letterKey,
      {required bool isPremium}) async {
    if (!isPremium) return '';
    if (!(await enabledLetters()).contains(letterKey)) return '';
    return configuredHtml();
  }

  /// HTML of the saved kop, or '' when it isn't configured.
  Future<String> configuredHtml() async {
    final kop = await get();
    if (!kop.isConfigured) return '';
    return KopSuratDesigns.html(
      kop,
      logoBase64: await logoBase64(kop.logoPath),
      secondaryLogoBase64: await logoBase64(kop.secondaryLogoPath),
    );
  }

  /// Whether [html] contains a kop generated by the app. Letters saved before
  /// kops were wrapped in the marker div are not detected.
  static bool hasKop(String html) => html.contains(KopSuratDesigns.markerClass);

  /// Removes the app-generated kop (marker div plus the empty paragraph
  /// after it) from [html].
  static String stripKop(String html) {
    final marker = html.indexOf(KopSuratDesigns.markerClass);
    if (marker < 0) return html;
    final start = html.lastIndexOf('<div', marker);
    if (start < 0) return html;

    // Walk nested <div>…</div> to find the wrapper's closing tag.
    final tag = RegExp(r'<div\b|</div>', caseSensitive: false);
    var depth = 0;
    var end = -1;
    for (final m in tag.allMatches(html, start)) {
      depth += m.group(0)!.toLowerCase() == '</div>' ? -1 : 1;
      if (depth == 0) {
        end = m.end;
        break;
      }
    }
    if (end < 0) return html;

    var rest = html.substring(end);
    final spacer = RegExp(r'^\s*<p><br\s*/?></p>', caseSensitive: false);
    rest = rest.replaceFirst(spacer, '');
    return html.substring(0, start) + rest;
  }

  Future<String?> logoBase64(String? path) async {
    if (path == null || path.isEmpty) return null;
    if (_isDataUri(path)) return path.split(',').last;
    final file = File(path);
    if (!await file.exists()) return null;
    return base64Encode(await file.readAsBytes());
  }

  static bool _isDataUri(String path) => path.startsWith('data:');

  // MemoryImage compares by byte-array identity, so decoding a data URI on
  // every build makes Flutter treat it as a new image and reload it (seen
  // while typing in the kop form on web). Reuse one provider per URI.
  static final Map<String, MemoryImage> _memoryImages = {};

  /// Image for a stored logo path, or null when there is no usable logo.
  static ImageProvider? logoImage(String? path) {
    if (path == null || path.isEmpty) return null;
    if (_isDataUri(path)) {
      return _memoryImages.putIfAbsent(
          path, () => MemoryImage(base64Decode(path.split(',').last)));
    }
    if (kIsWeb || !File(path).existsSync()) return null;
    return FileImage(File(path));
  }
}
